CREATE DATABASE IF NOT EXISTS retro_bank
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE retro_bank; 


DROP TABLE IF EXISTS TB_MOVIMENTACOES;
DROP TABLE IF EXISTS TB_CONTAS;
DROP TABLE IF EXISTS TB_TITULARES;
DROP TABLE IF EXISTS TB_USUARIOS;


CREATE TABLE TB_USUARIOS(
    ID_USUARIO INT PRIMARY KEY AUTO_INCREMENT,
    LOGIN VARCHAR(255) NOT NULL,
    SENHA VARCHAR(255) NOT NULL,
    SENHA_AUTH VARCHAR(255) NOT NULL 
) ENGINE=Innodb
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci
COMMENT='Tabela responsável por armazenar o usuario e credenciais dos titulares';


CREATE TABLE TB_TITULARES(
    ID_TITULAR INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL,
    SOBRE_NOME VARCHAR(255) NOT NULL,
    CPF VARCHAR(255) NOT NULL, 
    ID_USUARIO INT NOT NULL,

    CONSTRAINT FK_ID_USUARIO FOREIGN KEY(ID_USUARIO)
    REFERENCES TB_USUARIOS(ID_USUARIO)
    ON DELETE CASCADE 
    ON UPDATE CASCADE
) ENGINE=Innodb
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci
COMMENT='Tabela responsável por armazenar titular da conta';


CREATE TABLE TB_CONTAS(
    ID_CONTA INT PRIMARY KEY AUTO_INCREMENT,
    NU_CONTA INT NOT NULL,
    NU_AGENCIA INT NOT NULL,
    SALDO DOUBLE NOT NULL,
    TIPO_CONTA ENUM ('CORRENTE', 'POUPANÇA'),
    ID_TITULAR INT NOT NULL,

    CONSTRAINT FK_ID_TITULAR FOREIGN KEY(ID_TITULAR)
    REFERENCES TB_TITULARES(ID_TITULAR)
    ON DELETE CASCADE 
    ON UPDATE CASCADE
) ENGINE=Innodb
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci
COMMENT='Tabela responsável por armazenar as contas dos titulares';

CREATE TABLE TB_MOVIMENTACOES(
    ID_MOVIMENTACAO INT PRIMARY KEY AUTO_INCREMENT,
    TIPO_MOVIMENTACAO ENUM ('DEPOSITO', 'SAQUE', 'PIX', 'BOLETO', 'CARTAO DE CREDITO'), 
    VALOR DOUBLE NOT NULL,
    DESCRICAO VARCHAR(255) NOT NULL, 
    DATA_MOVIMENTACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ID_CONTA INT NOT NULL,

    CONSTRAINT FK_ID_CONTA FOREIGN KEY(ID_CONTA)
    REFERENCES TB_CONTAS(ID_CONTA)
    ON DELETE CASCADE 
    ON UPDATE CASCADE
) ENGINE=Innodb
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci
COMMENT='Tabela responsável por armazenar movimentações das contas';